class Participant:
    def __init__(
        self,
        name,
        age,
        sex,
        birthdate,
        email,
        cpnumber,
        address,
        category,
        distance,
        race_number
    ):
        self.name = name
        self.age = age
        self.sex = sex
        self.birthdate = birthdate
        self.email = email
        self.cpnumber = cpnumber
        self.address = address
        self.category = category
        self.distance = distance
        self.race_number = race_number